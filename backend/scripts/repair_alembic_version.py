"""Repair a broken alembic_version pointer WITHOUT touching any data.

Use this when ``alembic upgrade head`` fails with:

    Can't locate revision identified by '<some-hash>'

That happens when the database's alembic_version table contains a revision id
that no longer exists in ./alembic/versions (e.g. an old autogenerated
revision whose file was replaced by a renamed/cleaner one).

What this script does (safe, non-destructive):
  1. Connects using DATABASE_URL from backend/.env (same as the app).
  2. Reads the current alembic_version value(s).
  3. Verifies the target revision file exists in alembic/versions.
  4. UPDATEs alembic_version to the target id (default: '20261022_0003').

It NEVER drops tables, NEVER deletes rows from devices/sites/etc., and NEVER
creates/drops the database itself.

Usage (from the backend directory, venv active):
    python scripts/repair_alembic_version.py
    python scripts/repair_alembic_version.py --target 20261022_0003

Afterwards run:
    alembic upgrade head
"""
import argparse
import os
import re
import sys

# Make 'app' importable when run as: python scripts/repair_alembic_version.py
BACKEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BACKEND_DIR)

DEFAULT_TARGET = "20261022_0003"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", default=DEFAULT_TARGET,
                        help="Revision id present in alembic/versions to stamp.")
    args = parser.parse_args()

    # 1. Verify the target revision actually exists as a migration file.
    versions_dir = os.path.join(BACKEND_DIR, "alembic", "versions")
    found = False
    for fn in os.listdir(versions_dir):
        if not fn.endswith(".py"):
            continue
        with open(os.path.join(versions_dir, fn), encoding="utf-8") as fh:
            body = fh.read()
        if re.search(r'^revision\s*=\s*["\']%s["\']' % re.escape(args.target),
                    body, re.MULTILINE):
            found = True
            break
    if not found:
        print(f"ERROR: revision '{args.target}' not found in {versions_dir}. "
              f"Refusing to write an invalid pointer. Available ids:")
        for fn in sorted(os.listdir(versions_dir)):
            if fn.endswith(".py"):
                m = re.search(r'^revision\s*=\s*["\'](.+?)["\']',
                              open(os.path.join(versions_dir, fn),
                                   encoding="utf-8").read(), re.MULTILINE)
                if m:
                    print(f"  - {m.group(1)}  ({fn})")
        return 1

    # 2. Connect with the app's own DATABASE_URL.
    try:
        from dotenv import load_dotenv
        load_dotenv(os.path.join(BACKEND_DIR, ".env"))
    except ImportError:
        pass
    url = os.environ.get("DATABASE_URL")
    if not url:
        print("ERROR: DATABASE_URL is not set. Check backend/.env")
        return 1
    if "postgresql" not in url:
        print(f"NOTE: DATABASE_URL does not look like PostgreSQL ({url.split('://')[0]}://...). "
              "Continuing anyway; adjust --target if needed.")

    from sqlalchemy import create_engine, text
    engine = create_engine(url)

    with engine.begin() as conn:
        # 3. Show current state.
        try:
            rows = conn.execute(text("SELECT version_num FROM alembic_version")).fetchall()
        except Exception as e:
            print("ERROR: could not read alembic_version table:", e)
            print("If the table does not exist at all, run:  alembic stamp <revision>")
            return 1
        current = [r[0] for r in rows]
        print(f"Current alembic_version row(s): {current or '(empty table)'}")

        if current == [args.target]:
            print(f"Already correct ('{args.target}'). Nothing to do.")
            return 0

        # 4. Single UPDATE of the pointer only.
        conn.execute(text("DELETE FROM alembic_version"))
        conn.execute(text("INSERT INTO alembic_version (version_num) VALUES (:v)"),
                     {"v": args.target})
        print(f"Repaired: alembic_version -> '{args.target}'")

    print("\nNext step:  alembic upgrade head")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
